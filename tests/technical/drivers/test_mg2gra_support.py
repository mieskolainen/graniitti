# Verify generic integration keeps MadGraph HELAS numerical branches unchanged
def test_helas_transform_generated_function_bodies():
    support = load_module("mg5_support")
    layout = load_module("output_layout")
    raw = """#include "HelAmps_my_ufo.h"
#include <cstdlib>
using namespace std;
void HELAS::generated(double vmass, double pp, double p[4],
                      complex<double> M3, int nhel) {
  static complex<double> cI = complex<double>(0., 1.);
  if (vmass != 0.0) { pp = vmass; }
  if (pp == 0.0) { p[0] = pp; }
  if (p[1] == 0.0) { p[2] = p[1]; }
  if (M3 != 0.) { M3 = cI; }
  if (nhel == 0) { nhel = 1; }
  cerr << "Invalid helicity in txxxxx.";
  exit(1);
}
"""
    directory = layout.model_cpp_directory("my_ufo")
    converted = support.transform_helas_source(raw, "HelAmps_my_ufo.h", directory)
    expected = support.narrow_std_namespace(
        raw.replace(
            '#include "HelAmps_my_ufo.h"',
            f'#include "{layout.include_path(directory, "HelAmps_my_ufo.h")}"',
        )
    )

    assert converted == expected
    assert "if (vmass != 0.0)" in converted
    assert "if (pp == 0.0)" in converted
    assert "if (p[1] == 0.0)" in converted
    assert "if (M3 != 0.)" in converted
    assert "if (nhel == 0)" in converted
    assert "static std::complex<double> cI" in converted
    assert 'std::cerr << "Invalid helicity in txxxxx.";' in converted
    assert "exit(1);" in converted
    assert "fpclassify" not in converted
    assert "throw" not in converted


