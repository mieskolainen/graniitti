# Compute one malformed grouped source and its expected decoder diagnostic
def malformed_grouped_source(source, mutation):
    if mutation == "duplicate":
        return source.replace("t[2] = matrix_2();", "t[1] = matrix_2();"), "Duplicate"
    if mutation == "out_of_range":
        return source.replace("t[2] = matrix_2();", "t[3] = matrix_2();"), "Out-of-range"
    if mutation == "missing":
        return source.replace("  t[2] = matrix_2();\n", ""), "Missing sigmaKin"
    if mutation == "invalid_permutation":
        needle = "  perm[4] = 3;\n  calculate_wavefunctions"
        return source.replace(
            needle, "  perm[4] = 2;\n  calculate_wavefunctions"
        ), "Invalid generated"
    if mutation == "selected_out_of_range":
        return source.replace(
            "return matrix_element[2]", "return matrix_element[3]"
        ), "Out-of-range"
    if mutation == "selected_missing":
        return source.replace(
            "return matrix_element[2]", "return matrix_element[1]"
        ), "Missing sigmaHat"
    return (
        source.replace("t[2] = matrix_2();", "t[2] = matrix_2() + matrix_0();"),
        "Unsupported sigmaKin",
    )


