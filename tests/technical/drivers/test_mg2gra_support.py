# Build a synthetic grouped MG5 subprocess with selected leg permutations
def synthetic_grouped_subprocess(permutations, matrix_functions=None):
    class_name = "MG5_TEST_P1"
    nprocesses = len(permutations)
    nexternal = len(permutations[0])
    if matrix_functions is None:
        matrix_functions = tuple(f"matrix_{index}" for index in range(nprocesses))
    header = f"""
class {class_name} {{
  static const int ninitial = 2;
  static const int nexternal = {nexternal};
  static const int nprocesses = {nprocesses};
}};
"""
    evaluations = []
    for index, (permutation, matrix_function) in enumerate(
        zip(permutations, matrix_functions, strict=True)
    ):
        evaluations.extend(f"  perm[{leg}] = {value};" for leg, value in enumerate(permutation))
        evaluations.append("  calculate_wavefunctions(perm, helicities[0]);")
        evaluations.extend(f"  perm[{leg}] = {leg};" for leg in range(nexternal))
        evaluations.append(f"  t[{index}] = {matrix_function}();")
    sigma_hat = [
        f"  if (id1 == {index}) {{ return matrix_element[{index}]; }}"
        for index in range(nprocesses)
    ]
    unique_functions = tuple(dict.fromkeys(matrix_functions))
    matrix_blocks = []
    for index, matrix_function in enumerate(unique_functions):
        matrix_blocks.append(
            f"""
double {class_name}::{matrix_function}()
{{
  const int ncolor = 1;
  std::complex<double> jamp[ncolor];
  static const double denom[ncolor] = {{{index + 1}}};
  static const double cf[ncolor][ncolor] = {{{{{index + 2}}}}};
  // Calculate color flows
  jamp[0] = amp[{index}];
  // Sum and square the color flows to get the matrix element
  return 0.0;
}}
"""
        )
    denominators = ", ".join(str(4 * (index + 1)) for index in range(nprocesses))
    helicities = ", ".join("-1" if index % 2 == 0 else "1" for index in range(nexternal))
    source = f"""
void {class_name}::sigmaKin()
{{
  const int ncomb = 1;
  const int helicities[ncomb][nexternal] = {{{{{helicities}}}}};
  const int denominators[nprocesses] = {{{denominators}}};
  double t[nprocesses];
  int perm[nexternal];
  for (int leg = 0; leg < nexternal; ++leg) {{ perm[leg] = leg; }}
{chr(10).join(evaluations)}
}}

double {class_name}::sigmaHat()
{{
{chr(10).join(sigma_hat)}
  return 0.;
}}
{"".join(matrix_blocks)}
"""
    return class_name, header, source


