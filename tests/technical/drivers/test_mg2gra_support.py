# Verify last-model cleanup retires only support without an active owner
def test_orphan_active_model_suffix(tmp_path, monkeypatch):
    regenerate = load_module("regenerate")
    layout = load_module("output_layout")
    for model, suffix in (("old_model", "old"), ("active_model", "active")):
        directory = layout.model_cpp_directory(model)
        for filename, content in (
            (f"HelAmps_{suffix}.h", "header\n"),
            (f"Parameters_{suffix}.h", "header\n"),
        ):
            path = tmp_path / layout.header_path(directory, filename)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        for filename in (f"HelAmps_{suffix}.cc", f"Parameters_{suffix}.cc"):
            path = tmp_path / layout.cpp_source_path(directory, filename)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("source\n")
    export = tmp_path / "export"
    write_support_export(export, "active")
    monkeypatch.setattr(regenerate, "ROOT", tmp_path)
    transaction = regenerate.InstallTransaction(tmp_path / "journal")

    regenerate.retire_orphaned_model_support({"active_model": export}, transaction)

    old_directory = layout.model_cpp_directory("old_model")
    active_directory = layout.model_cpp_directory("active_model")
    assert not (tmp_path / layout.header_path(old_directory, "HelAmps_old.h")).exists()
    assert not (tmp_path / layout.cpp_source_path(old_directory, "Parameters_old.cc")).exists()
    assert (tmp_path / layout.header_path(active_directory, "HelAmps_active.h")).is_file()
    assert (tmp_path / layout.cpp_source_path(active_directory, "Parameters_active.cc")).is_file()


