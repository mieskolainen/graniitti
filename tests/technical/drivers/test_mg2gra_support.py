# Verify rollback restores all prior outputs after a partly completed commit
def test_install_rolls_back_partial_commit(tmp_path, monkeypatch):
    regenerate = load_module("regenerate")
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    first.write_text("old first\n")
    second.write_text("old second\n")
    journal_root = tmp_path / "journal"
    transaction = regenerate.InstallTransaction(journal_root)
    regenerate.install_text(first, "new first\n", transaction)
    regenerate.install_text(second, "new second\n", transaction)
    move_file = regenerate.move_file
    commits = 0

    def fail_second_commit(source, destination):
        nonlocal commits
        if destination.name.endswith("._old"):
            commits += 1
            if commits == 2:
                raise OSError("injected commit failure")
        move_file(source, destination)

    monkeypatch.setattr(regenerate, "move_file", fail_second_commit)
    with pytest.raises(OSError, match="injected commit failure"):
        transaction.commit()
    transaction.rollback()

    assert first.read_text() == "old first\n"
    assert second.read_text() == "old second\n"
    assert not list(tmp_path.glob("*.txt._old*"))
    failed = {path.read_text() for path in journal_root.rglob("failed_*")}
    assert failed == {"new first\n", "new second\n"}


