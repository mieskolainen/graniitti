# Load one MG2GRA module from the repository without relying on the working directory
def load_module(name):
    root = Path(__file__).resolve().parents[3]
    module_dir = root / "develop/MG2GRA"
    qualified = name if name == "regenerate" else f"modules.{name}"
    sys.path.insert(0, str(module_dir))
    try:
        module = importlib.import_module(qualified)
    finally:
        sys.path.remove(str(module_dir))
    return module


# Preserve spinor normalization when the longitudinal sum cancels
@pytest.mark.parametrize("momentum", ["pp", "p[0]"])
@pytest.mark.parametrize("maximum", ["max", "std::max"])
@pytest.mark.parametrize("zero", ["0.0", "0.00"])
def test_helas_conversion_rationalizes_spinors(momentum, maximum, zero):
    converter = load_module("mg5_support")
    source = f"pp3 = {maximum}({momentum} + p[3], {zero});"
    result = converter.transform_helas_source(source, "HelAmps_sm.h", "Runtime/Models/sm")
    assert result == (
        "pp3 = (p[3] < 0.0 ? (p[1] * p[1] + p[2] * p[2]) / "
        f"({momentum} - p[3]) : {momentum} + p[3]);"
    )
    assert converter.transform_helas_source(result, "HelAmps_sm.h", "Runtime/Models/sm") == result


