# Compute every active non-helper icepack dataset in stable order
def icepack_datasets():
    datasets = []
    for path in sorted(ICEPACK_ROOT.rglob("dataset.json")):
        relative = path.relative_to(ICEPACK_ROOT)
        if any(part.startswith("_") or "._old" in part for part in relative.parts):
            continue
        with path.open(encoding="utf-8") as stream:
            dataset = json5.load(stream)
        if dataset.get("active", False):
            datasets.append(path)
    return tuple(datasets)


DATASETS = icepack_datasets()
INTEGRATED_DATASETS = tuple(
    path
    for path in DATASETS
    if json5.loads(path.read_text(encoding="utf-8")).get("type") in {"INTEGRATED_LITERATURE", "INTEGRATED_HEPDATA"}
)
UNIT_LABELS = {3: "mb", 6: "ub", 9: "nb", 12: "pb", 15: "fb"}


